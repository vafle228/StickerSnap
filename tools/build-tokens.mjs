// tokens.json (design system v6) → tokens.css.
// Usage: node tools/build-tokens.mjs [--check]
// --check fails when the committed tokens.css is stale (used by CI).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dsDir = fileURLToPath(new URL("../src/web/src/ds/", import.meta.url));
const source = `${dsDir}tokens.json`;
const target = `${dsDir}tokens.css`;
const tokens = JSON.parse(readFileSync(source, "utf8"));

const themeIds = tokens.color.themes.map((t) => t.id);
const ref = (value) => String(value).replace(/\{([a-z0-9-]+)\}/g, "var(--$1)");
const decl = (name, value) => `  --${name}: ${ref(value)};`;
const isThemed = (value) => typeof value === "object" && value !== null;

// Values shared by both themes go to :root, per-theme values to [data-theme].
// A reference ("{prism-peach}") is repeated in every theme block so that it resolves
// against the theme of the subtree, not only of the root.
const shared = [];
const themed = Object.fromEntries(themeIds.map((id) => [id, []]));
const add = (name, value) => {
  if (isThemed(value)) for (const id of themeIds) themed[id].push(decl(name, value[id]));
  else if (String(value).includes("{"))
    for (const id of themeIds) themed[id].push(decl(name, value));
  else shared.push(decl(name, value));
};

for (const t of tokens.color.tokens) add(t.name, t.value);
shared.push(decl("font-sans", tokens.type.families.sans));
shared.push(decl("font-mono", tokens.type.families.mono));
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    shared.push(
      decl(
        `type-${s.name}`,
        `${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-${group.family})`,
      ),
    );
    if (s.letterSpacing) shared.push(decl(`type-${s.name}-tracking`, s.letterSpacing));
  }
}
for (const section of ["spacing", "radius", "shadow", "timing", "size"]) {
  for (const t of tokens[section].tokens) add(t.name, t.value);
}

// Accent classes (R20): the class on the app root swaps the primary family.
const accents = [
  ...new Set(
    tokens.color.tokens.map((t) => /^accent-([a-z]+)-primary$/.exec(t.name)?.[1]).filter(Boolean),
  ),
];
const accentList = accents.map((a) => `.ss-accent-${a}`).join(", ");
const accentRules = accents.map(
  (a) =>
    `.ss-accent-${a} { --primary: var(--accent-${a}-primary); --on-primary: var(--accent-${a}-on); ` +
    `--primary-ink: var(--accent-${a}-ink); --primary-soft: var(--accent-${a}-soft); --primary-hover: var(--accent-${a}-hover); }`,
);

const [defaultTheme] = themeIds;
const css = `/* Generated by tools/build-tokens.mjs from tokens.json (${tokens.name} v${tokens.version}). Do not edit by hand. */

:root {
${shared.join("\n")}
}

${themeIds
  .map(
    (id) =>
      `${id === defaultTheme ? ":root, " : ""}[data-theme="${id}"] {\n${themed[id].join("\n")}\n}`,
  )
  .join("\n\n")}

/* Accents (R20): one class on the app root recolors primary, selection, focus and the primary glow.
   Notification tones, highlight and the rainbow stay. */
${accentRules.join("\n")}
:is(${accentList}) {
  --focus: var(--primary); --shadow-primary: 0 6px 14px color-mix(in srgb, var(--primary) 30%, transparent); }
[data-theme="dark"] :is(${accentList}),
:is(${accentList})[data-theme="dark"] {
  --focus: var(--primary-ink); --shadow-primary: 0 6px 14px color-mix(in srgb, var(--primary) 26%, transparent); }
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // missing file is stale too
  }
  if (current.replace(/\r\n/g, "\n") !== css) {
    console.error("tokens.css is out of date: run `npm run gen:tokens` and commit the result.");
    process.exit(1);
  }
  console.log("tokens.css is up to date.");
} else {
  writeFileSync(target, css);
  console.log(`Wrote ${target}`);
}
