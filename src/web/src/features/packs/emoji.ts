/** Emoji whose words start with what was typed: «кот» finds 😺 😹 🙀 😻 🐈. */
export function searchEmoji(query: string): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const found = EMOJI_GROUPS.flatMap((g) => g.list)
    .filter(([emoji, words]) => emoji === q || words.split(" ").some((w) => w.startsWith(q)))
    .map(([emoji]) => emoji);
  return [...new Set(found)];
}
